param([string]$UnityEditor)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Common.ps1')
$editor = Find-UnityEditor $UnityEditor
$sourceRoot = Split-Path -Parent $PSScriptRoot
$buildRoot = $sourceRoot
if ($sourceRoot -match '[^\x00-\x7F]') { $buildRoot = & (Join-Path $PSScriptRoot 'Stage-AndroidWorkspace.ps1') }
$results = Join-Path $sourceRoot 'TestResults'
New-Item -ItemType Directory -Path $results -Force | Out-Null
$log = Join-Path $results 'AndroidBuild.log'
$started = Get-Date
$arguments = @('-batchmode', '-nographics', '-projectPath', ('"' + $buildRoot + '"'), '-buildTarget', 'Android', '-executeMethod', 'QuestCounter.Editor.QuestProjectTools.BuildQuestApk', '-quit', '-logFile', ('"' + $log + '"'))
$process = Start-Process -FilePath $editor -ArgumentList $arguments -WindowStyle Hidden -Wait -PassThru
$exitCode = $process.ExitCode
if ($exitCode -ne 0) { throw "Unity build failed (exit $exitCode). Read $log" }
$apk = Join-Path $buildRoot 'Builds\QuestRayCounter.apk'
if (-not (Test-Path -LiteralPath $apk)) { throw "Unity produced no APK. Read $log" }
if ((Get-Item -LiteralPath $apk).LastWriteTime -lt $started) { throw 'APK was not generated by this run.' }
if ($buildRoot -ne $sourceRoot) {
    $out = Join-Path $sourceRoot 'Builds'; New-Item -ItemType Directory -Path $out -Force | Out-Null
    Copy-Item -LiteralPath $apk -Destination (Join-Path $out 'QuestRayCounter.apk') -Force
    $apk = Join-Path $out 'QuestRayCounter.apk'
}
Write-Host "APK ready: $apk"
Write-Host 'An APK build is not a headset test. Install on the Quest 2 and complete the acceptance steps.'
